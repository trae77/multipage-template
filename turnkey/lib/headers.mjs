// One source for security headers: written to dist/_headers (static assets) and used by the Worker for API/owner responses.
export const CSP = [
  "default-src 'self'", "script-src 'self' https://challenges.cloudflare.com", "style-src 'self'",
  "img-src 'self' data:", "font-src 'self'", "connect-src 'self' https://challenges.cloudflare.com",
  "frame-src https://challenges.cloudflare.com https://www.google.com", "form-action 'self'",
  "frame-ancestors 'none'", "base-uri 'self'", "object-src 'none'", 'upgrade-insecure-requests',
].join('; ');
export const SECURITY_HEADERS = {
  'Content-Security-Policy': CSP,
  'Strict-Transport-Security': 'max-age=300',
  'X-Frame-Options': 'DENY',
  'X-Content-Type-Options': 'nosniff',
  'Referrer-Policy': 'strict-origin-when-cross-origin',
  'Permissions-Policy': 'camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=()',
  'X-Robots-Tag': 'noindex, nofollow',
};
export const REQUIRED_HEADERS = Object.keys(SECURITY_HEADERS);
export function headersFile() {
  const lines = ['# Generated by turnkey/lib/build.mjs. Do not hand-edit. Previews are noindex.', '/*'];
  for (const [k, v] of Object.entries(SECURITY_HEADERS)) lines.push(`  ${k}: ${v}`);
  lines.push('/owner/*', '  Cache-Control: private, no-store', '/demo/*', '  Cache-Control: no-store');
  return lines.join('\n') + '\n';
}
